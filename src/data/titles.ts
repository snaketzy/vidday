function buildSeasons(titleId: string, seasons: RawSeason[]): Season[] {
  return seasons.map((season) => ({
    number: season.number,
    title: season.title ?? `第 ${season.number} 季`,
    episodes: season.episodes.map(
      (episode, index): Episode => ({
        id: `${titleId}-s${season.number}e${index + 1}`,
        season: season.number,
        number: index + 1,
        title: episode.title,
        synopsis: episode.synopsis,
        duration: episode.duration,
      }),
    ),
  }))
}

